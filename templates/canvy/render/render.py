def main():
    doc = json.load(sys.stdin)
    body = doc.get("body") or {}
    env = doc.get("envelope") or {}
    header = env.get("header") or {}
    hop = header.get("hop") or {}

    ctx = header.get("context") or {}

    # WHICH PASS THIS IS, decided by edge authority and nothing else.
    #
    # `canvy_origin` is stamped by the hive's `./render -> ./store` edge, so it is
    # on the store's reply and on nothing an HTTP request carries. Deciding this by
    # inspecting the body instead — "did it parse as rows?" — turned every store
    # error into an infinite render/store loop that stopped only at the TTL. A
    # discriminator has to be unambiguous, and only an edge can make it so.
    if str(ctx.get("canvy_origin") or "") != "render":
        # ---- pass 1: a request came in. Ask the store for everything.
        req = body.get("surface") or {}
        # `columns` is REQUIRED by the store — a select without it answers
        # "missing columns array", which is how the loop above was found.
        out = store_op(
            "select",
            table="canvas",
            columns=["kind", "id", "x", "y", "z", "doc"],
            limit=100000,
        )
        # The request rides along in `hop`, and the hive's `./render -> ./store`
        # edge promotes it into `context`. That promotion is not decoration: `hop`
        # survives exactly ONE edge, and pass 2 is two edges away
        # (render -> store -> render). Carrying it in `hop` alone looked right and
        # silently lost every drop — the box came back at its automatic position.
        out["header"]["event"] = str(req.get("event") or "")
        value = req.get("value") or {}
        out["header"]["moved_id"] = str(value.get("id") or "")
        out["header"]["moved_x"] = str(value.get("x") or "")
        out["header"]["moved_y"] = str(value.get("y") or "")
        out["header"]["cam"] = json.dumps(value.get("camera") or {})
        return [out]

    # ---- pass 2: the store answered.
    rows = rows_of(body)
    if hop.get("error_code"):
        # A refused write. One corrective render, because a picture claiming a
        # position the database does not hold is worse than a visible failure.
        return [
            surface_reply(
                {"error": "the canvas store refused a write: %s" % hop.get("error_code")}
            )
        ]

    if rows is None:
        # The store answered, and it was not a result set. One visible failure,
        # never a retry: a retry against a store that just refused is a loop.
        return [
            surface_reply(
                {"error": "the canvas store did not return rows: %s" % last_text(body)[:200]}
            )
        ]

    saved = {}
    hive_at = {}
    camera = (0, 0, 1000)
    graph = {}
    for r in rows:
        kind = r.get("kind")
        if kind == "node":
            try:
                saved[str(r.get("id"))] = (int(r.get("x") or 0), int(r.get("y") or 0))
            except (TypeError, ValueError):
                continue
        elif kind == "hive":
            # Where a GROUP was put. Same shape as a node row, different `kind`.
            try:
                hive_at[str(r.get("id"))] = (int(r.get("x") or 0), int(r.get("y") or 0))
            except (TypeError, ValueError):
                continue
        elif kind == "camera":
            try:
                camera = (
                    int(r.get("x") or 0),
                    int(r.get("y") or 0),
                    int(r.get("z") or 1000),
                )
            except (TypeError, ValueError):
                pass
        elif kind == "graph":
            graph = as_doc(r.get("doc"))

    raw_nodes = graph.get("nodes") or []
    raw_edges = graph.get("edges") or []
    if not isinstance(raw_nodes, list) or not isinstance(raw_edges, list):
        return [surface_reply({"error": "the topology snapshot is malformed"})]
    if not raw_nodes:
        return [
            surface_reply(
                {
                    "error": "no topology snapshot yet — the refresh timer has not "
                    "run, or /colony/graph answered nothing"
                }
            )
        ]

    edges = edge_lanes(
        [
            {
                "id": str(e.get("id") or ""),
                "from": str(e.get("from") or "").strip("/"),
                "to": str(e.get("to") or "").strip("/"),
                "condition": e.get("condition"),
            }
            for e in raw_edges
            if isinstance(e, dict)
        ]
    )

    # A move overrides both the saved position and the automatic one. This is
    # what keeps the picture and the database from disagreeing: the box is
    # rendered where it is written, from ONE input.
    # From `context`, not from `hop`: see the promotion in the hive's edge.
    moved_id = str(ctx.get("canvy_moved_id") or "")
    event = str(ctx.get("canvy_event") or "")
    writes = []
    if moved_id and event == "hive:moved":
        # A group was dropped. One row for the group — never one per member: a
        # 20-cell hive would otherwise cost 40 store round trips on an
        # interactive path, and the members' own rows would then have to be kept
        # consistent with a box nobody stores.
        try:
            hx, hy = int(ctx.get("canvy_moved_x")), int(ctx.get("canvy_moved_y"))
        except (TypeError, ValueError):
            hx = hy = None
        if hx is not None:
            hive_at[moved_id] = (hx, hy)
            writes.append(
                store_op("delete", table="canvas", where={"kind": "hive", "id": moved_id})
            )
            writes.append(
                store_op(
                    "insert",
                    table="canvas",
                    row={"kind": "hive", "id": moved_id, "x": hx, "y": hy},
                )
            )
    elif moved_id:
        try:
            mx, my = int(ctx.get("canvy_moved_x")), int(ctx.get("canvy_moved_y"))
        except (TypeError, ValueError):
            mx = my = None
        if mx is not None:
            saved[moved_id] = (mx, my)
            # Delete then insert, in one emission and in that order: a position is
            # presentation state, so the row is REPLACED rather than appended. The
            # no-delete promise protects what was said and what was learned; where
            # a rectangle sits is neither.
            writes.append(
                store_op("delete", table="canvas", where={"kind": "node", "id": moved_id})
            )
            writes.append(
                store_op(
                    "insert",
                    table="canvas",
                    row={"kind": "node", "id": moved_id, "x": mx, "y": my},
                )
            )

    nodes = []
    for n in raw_nodes:
        if not isinstance(n, dict):
            continue
        path = str(n.get("path") or "").strip("/")
        if not path:
            continue
        ctype = str(n.get("cell_type") or "")
        fill, stroke = TYPE_COLOR.get(ctype, DEFAULT_COLOR)
        nodes.append(
            {
                "id": path,
                "name": path.rsplit("/", 1)[-1],
                "type": ctype,
                "fill": fill,
                "stroke": stroke,
            }
        )

    pos = auto_layout(nodes, edges, saved, hive_at)
    for n in nodes:
        n["x"], n["y"] = pos[n["id"]]
    hives = hive_boxes(nodes, pos)

    html = render(nodes, hives, edges, camera, graph.get("scope") or "/")
    return writes + [surface_reply({"html": html})]


if __name__ == "__main__":
    out = main()
    sys.stdout.write(json.dumps(out if len(out) > 1 else out[0]))
