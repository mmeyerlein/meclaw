"""The surface: layout, markup, and the one write that keeps them honest.

THIS FILE IS THE SOURCE. `config.json` carries a copy of it in `script_inline`,
generated by `scripts/canvy_sync.py` and pinned by a test in
`crates/meclaw-cells/tests/canvy_template.rs`. Edit here, then run:

    python3 scripts/canvy_sync.py

Why the copy exists at all: a `code` cell's `script_path` is handed to the
interpreter verbatim with no working directory of its own (the factory ignores
`cell_dir` — `code` is stateless), so a relative path would resolve against the
daemon's cwd, and an absolute path baked into a template is the exported-tree
defect class of GH #20. So the runtime form is `script_inline`, and this file is
what a person reads, greps, diffs and runs:

    python3 templates/canvy/render/render.py < some-store-answer.json

# What this cell is, and what it is not

It is the whole picture. Every tag, every colour, every coordinate is decided
here, which is what makes a new object type a template change instead of a
release. The binary that serves it knows none of this.

It is NOT the owner of the topology. That comes from `/colony/graph`, by message,
into this hive's own store, on a timer — never read out of a database, and never
fetched inside a browser's request (a `/colony` reply arrives on a fresh envelope
with no context, so it could not be correlated back to the browser that asked).

# The two passes

Pass 1 (a request from the HTTP layer): remember what was asked in `hop`, emit one
`select` over the whole `canvas` table.

Pass 2 (the store's answer): compute the layout, render everything, emit the HTML
on the surface lane — and, if the request carried a move, emit the layout write in
the same pass. The box is rendered exactly where it is written, from one input, so
the picture and the database cannot disagree.
"""
import json
import sys
import uuid

# The layout constants, from the Python reference this ports (topology_html.py).
NODE_W, NODE_H = 150, 38
GAP_X, GAP_Y = 60, 40
PAD_TOP, PAD_SIDE, PAD_BOT = 30, 24, 24
# How wide a shelf of hives may grow before the next one wraps to a new row, and
# the air between two hive boxes. `SHELF_W` is a target and not a limit: a single
# hive wider than this still gets its own row rather than being cut.
SHELF_W = 2400
HIVE_GAP_X, HIVE_GAP_Y = 90, 80
# How much more room each level towards the ROOT gets, so an ancestor's frame
# strictly contains its descendants' instead of sharing an edge.
NEST_PAD = 14
# How many depths the stylesheet has a tint for. Deeper hives keep the last one.
# Ten, because a real colony gets deep: `/org/<org>/member/<who>/assistants/<name>/
# talky/keeper` is already eight, and two hives at different depths sharing a colour
# is exactly the thing the tint exists to prevent.
HIVE_DEPTH_TINTS = 10

# Fill and stroke per cell type. Ported verbatim from colony_topology.py so the
# shipped surface and the standalone renderer draw the same colony.
