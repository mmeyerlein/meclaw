def read_objects(body):
    """`{id: props}` out of a `query` answer, or None when it was not one."""
    msgs = body.get("messages") or []
    if not msgs:
        return None
    try:
        doc = json.loads(str(msgs[-1].get("text") or ""))
    except Exception:
        return None
    if not isinstance(doc, dict) or not isinstance(doc.get("objects"), list):
        return None
    out = {}
    for o in doc["objects"]:
        if isinstance(o, dict) and o.get("id"):
            props = o.get("props")
            out[str(o["id"])] = props if isinstance(props, dict) else {}
    return out


def saved_positions(have):
    """The positions the display already holds, in the layout's own space.

    This is the entire persistence story of a drag: the browser wrote `x` and `y`
    into the object, and the next tick reads them back and leaves them alone.
    """
    saved = {}
    for oid, props in have.items():
        if not oid.startswith(NODE_PREFIX):
            continue
        try:
            saved[oid[len(NODE_PREFIX):]] = (int(props.get("x")), int(props.get("y")))
        except (TypeError, ValueError):
            continue
    return saved


def main():
    doc = json.load(sys.stdin)
    body = doc.get("body") or {}
    header = (doc.get("envelope") or {}).get("header") or {}
    hop = header.get("hop") or {}
    ctx = header.get("context") or {}
    origin = str(ctx.get("canvy_origin") or "")

    # ---- pass 3 FIRST, because it is the terminating one.
    #
    # The display has answered a patch. There is nothing left to do, and this is
    # the only place that can say so: `canvy_origin` is stamped by the hive's
    # `./layout -> ./web` edge and travels back on the reply. Getting this wrong
    # is not a cosmetic bug -- see the GH #161 paragraph in the module docstring.
    if origin == "patch":
        return []

    # ---- pass 2: the display answered the query.
    if origin == "layout":
        raw = str(ctx.get("canvy_graph") or "")
        try:
            snap = json.loads(raw) if raw else None
        except Exception:
            snap = None
        if not isinstance(snap, dict) or not snap.get("nodes"):
            # No snapshot to draw. Silence rather than a half-picture: the timer
            # will bring the next one, and a display that emptied itself because
            # one message was malformed is worse than one that is a minute stale.
            return []

        have = read_objects(body)
        # A refusal is the BOOTSTRAP signal and the only one there is: a `web`
        # cell whose `pages` table has no `/` answers `query` with `invalid_input`.
        bootstrap = have is None
        if bootstrap:
            have = {}
        want = build(snap, saved_positions(have))
        calls = patches(want, have, bootstrap)
        if not calls:
            return []
        return [emission("patch", [tool_call(c) for c in calls])]

    # ---- pass 1: a snapshot arrived from the probe. Ask what the display holds.
    #
    # The graph goes out on `hop`, where the hive's edge picks it up and promotes
    # it into `context`; there is nowhere else to put it, because the display's
    # reply carries no body of ours and a `code` cell has no memory between calls.
    graph = body.get("graph")
    if not isinstance(graph, dict):
        return []
    snap = compact(graph)
    if not snap["nodes"]:
        return []
    return [
        emission(
            "read",
            [tool_call({"op": "query", "route": "/"})],
            canvy_graph=json.dumps(snap, sort_keys=True),
        )
    ]


if __name__ == "__main__":
    out = main()
    # A single emission is written as an object, several as an array -- and an
    # empty list stays an empty array, which is how a `code` cell says "nothing to
    # send" (`parse_stdout_json`: a top-level array of length 0 is zero emissions).
    # The `out[0]` shorthand this replaces raised IndexError on that case, which is
    # exactly the pass this cell most needs to survive.
    sys.stdout.write(json.dumps(out[0] if len(out) == 1 else out))
