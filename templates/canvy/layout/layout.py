# Talking to the `web` cell


def tool_call(args):
    """One `object.*` call, as a UBF `tool_call` turn."""
    return {
        "origin": "assistant",
        "type": "tool_call",
        "id": uuid.uuid4().hex[:12],
        "text": json.dumps(args, sort_keys=True),
    }


def emission(route, turns, **header):
    """One message on `route`, carrying `turns` as its tool calls.

    `messages` is mandatory and not decoration: every body crossing the substrate
    is validated as a UBF document, and one without that slot is rejected as
    `invalid_ubf_body` -- the emission never reaches an edge, so it shows up as a
    dead letter from this cell and as a picture that silently stops updating.
    """
    head = {"route": route}
    head.update(header)
    return {"header": head, "messages": turns}


def compact(graph):
    """The projection this cell needs, and nothing else.

    It travels through `context` (see the module docstring), so every byte is one
    a header carries twice. Positional rows rather than objects for the same
    reason: `[[path, type], ...]` is roughly half of `[{"path":…,"type":…}, …]`
    for the same content.
    """
    nodes = []
    for n in graph.get("nodes") or []:
        if not isinstance(n, dict):
            continue
        path = str(n.get("path") or "").strip("/")
        if path:
            nodes.append([path, str(n.get("cell_type") or "")])
    edges = []
    for e in graph.get("edges") or []:
        if not isinstance(e, dict):
            continue
        mod = e.get("modifier")
        edges.append([
            str(e.get("id") or ""),
            str(e.get("from") or "").strip("/"),
            str(e.get("to") or "").strip("/"),
            str(e.get("condition") or ""),
            json.dumps(mod, sort_keys=True) if mod else "",
        ])
    return {"scope": str(graph.get("scope") or "/"), "nodes": nodes, "edges": edges}


def desired_objects(snap):
    """Every object this picture should hold, keyed by id.

    Positions are the flow layout's; the caller overrules them for whatever the
    display already knows, which is what keeps a drag.
    """
    nodes_in = snap.get("nodes") or []
    edges_in = snap.get("edges") or []

    edges = edge_lanes([
        {"id": e[0], "from": e[1], "to": e[2], "cond": e[3], "mod": e[4]}
        for e in edges_in
        if isinstance(e, list) and len(e) >= 5
    ])
    wired = {e["from"] for e in edges} | {e["to"] for e in edges}
    nodes = [
        {"id": n[0], "name": n[0].rsplit("/", 1)[-1], "type": n[1]}
        for n in nodes_in
        if isinstance(n, list) and len(n) >= 2 and n[0]
    ]
    for n in nodes:
        n["unwired"] = n["id"] not in wired
    return nodes, edges


def build(snap, saved):
    """The whole desired object set: `{id: {component, parent, ord, props}}`."""
    nodes, edges = desired_objects(snap)
    pos = auto_layout(nodes, [{"from": e["from"], "to": e["to"]} for e in edges], saved)
    for n in nodes:
        n["x"], n["y"] = pos.get(n["id"], (0, 0))
    hives = hive_boxes(pos)
    box = frame(nodes, hives)

    want = {}
    want[ROOT_ID] = {
        "component": "canvy-shell",
        "parent": None,
        "ord": 0,
        "props": {
            "title": snap.get("scope") or "/",
            "viewbox": "%d %d %d %d" % box,
            "cells": len(nodes),
            "hives": len(hives),
            "edges": len(edges),
            "nw": NODE_W,
            "nh": NODE_H,
            "pad_side": PAD_SIDE,
            "pad_top": PAD_TOP,
            "pad_bot": PAD_BOT,
            "nest": NEST,
        },
    }
    # Hives first, then edges, then cells: `ord` is the draw order, and a line
    # under a box reads as a line while a box under a line reads as a mistake.
    for h in hives:
        want[HIVE_PREFIX + h["id"]] = {
            "component": "canvy-hive",
            "parent": ROOT_ID,
            "ord": 100 + h["depth"],
            "props": {
                "path": h["id"],
                "name": h["name"],
                "depth": max(1, min(HIVE_DEPTH_TINTS, h["depth"])),
                "x": h["x"],
                "y": h["y"],
                "w": h["w"],
                "h": h["h"],
                "tx": h["x"] + 8,
                "ty": h["y"] + 18,
            },
        }
    for e in edges:
        want[EDGE_PREFIX + e["id"]] = {
            "component": "canvy-edge",
            "parent": ROOT_ID,
            "ord": 2000,
            "props": {
                "eid": e["id"],
                "from": e["from"],
                "to": e["to"],
                "lane": e.get("lane", 0),
                "cond": e["cond"],
                "mod": e["mod"],
            },
        }
    for n in nodes:
        fill, stroke = TYPE_COLOR.get(n["type"], DEFAULT_COLOR)
        want[NODE_PREFIX + n["id"]] = {
            "component": "canvy-node",
            "parent": ROOT_ID,
            "ord": 3000,
            "props": {
                "path": n["id"],
                "oid": NODE_PREFIX + n["id"],
                "name": n["name"],
                "type": n["type"],
                "x": n["x"],
                "y": n["y"],
                "w": NODE_W,
                "h": NODE_H,
                "fill": fill,
                "stroke": stroke,
                # A prop the `{{#if}}` has to read as absent when it is false, and
                # the empty string is how this template language spells that.
                "unwired": "1" if n["unwired"] else "",
            },
        }
    return want


def patches(want, have, bootstrap):
    """The calls that turn `have` into `want`, in an order the display accepts.

    Components before objects, the root before its children, the page after its
    root -- one bundle, applied in call order, so a fresh display and a running
    one take exactly the same path.
    """
    calls = []
    if bootstrap:
        for c in components():
            calls.append({"op": "component.define", **c})
        root = want[ROOT_ID]
        props = dict(root["props"])
        # The client rides in on the bootstrap and is never sent again: it is by
        # far the largest thing this cell says, and it does not change between
        # ticks. `object.update` merges per key, so leaving it out of every later
        # patch keeps it exactly as it is.
        props["client_css"] = CLIENT_CSS
        props["client_js"] = CLIENT_JS
        calls.append({
            "op": "object.create",
            "id": ROOT_ID,
            "component": root["component"],
            "ord": root["ord"],
            "props": props,
        })
        calls.append({"op": "page.set", "route": "/", "root": ROOT_ID,
                      "title": "canvy"})
    elif ROOT_ID in want:
        calls.append({"op": "object.update", "id": ROOT_ID,
                      "props": want[ROOT_ID]["props"]})

    for oid in sorted(k for k in want if k != ROOT_ID):
        spec = want[oid]
        if oid in have:
            calls.append({"op": "object.update", "id": oid, "props": spec["props"]})
        else:
            calls.append({
                "op": "object.create",
                "id": oid,
                "component": spec["component"],
                "parent": spec["parent"],
                "ord": spec["ord"],
                "props": spec["props"],
            })

    # What the colony no longer has. 1.x could not do this: a row naming a cell
    # that had vanished was indistinguishable from a rename, so the deletion was
    # an operator's button (`canvas:sweep`, GH #184). Here the objects ARE the
    # picture rather than a side table beside it -- an object with no cell behind
    # it is not stale bookkeeping, it is a box drawn for something that is gone.
    # Deleted leaf-first, because the display refuses to cascade.
    for oid in sorted((k for k in have if k != ROOT_ID and k not in want), reverse=True):
        calls.append({"op": "object.delete", "id": oid})
    return calls


