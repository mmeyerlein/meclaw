"""The layout: a topology snapshot in, object patches for a `web` cell out.

THIS FILE IS THE SOURCE. `config.json` carries a copy of it in `script_inline`,
generated by `scripts/canvy_sync.py` and pinned by a test in
`crates/meclaw-cells/tests/canvy2_pipeline.rs`. Edit here, then run:

    python3 scripts/canvy_sync.py

Why the copy exists at all: a `code` cell's `script_path` is handed to the
interpreter verbatim with no working directory of its own (the factory ignores
`cell_dir` -- `code` is stateless), so a relative path would resolve against the
daemon's cwd, and an absolute path baked into a template is the exported-tree
defect class of GH #20. So the runtime form is `script_inline`, and this file is
what a person reads, greps, diffs and runs:

    python3 templates/canvy/layout/layout.py < some-web-answer.json

The same generator substitutes `client.js` and `client.css` into the two
constants below, which is why they read as placeholders here and as the real
files in `config.json`.

# What this cell is

It is the whole picture, and it draws it as OBJECTS rather than as HTML. The
`web` cell holds an object tree, a component library and a page; this cell says
what belongs in that tree. A new kind of thing on the canvas is therefore a
template edit -- one more component and one more patch -- and never a release.

It is NOT the owner of the topology. That comes from `/colony/graph`, by message,
through this hive's own `./probe` lane, on a timer -- never read out of a
database, and never fetched inside a browser's request (a `/colony` reply arrives
on a fresh envelope with no context, so it could not be correlated back to
whoever asked).

It is also NOT the owner of a position. A cell the display already knows keeps
the `x`/`y` it has, because a person may have dragged it there and a drag is a
LOCAL write inside the `web` cell that nothing here ever hears about. Only a
cell the display has never seen is given a computed spot. That is the whole of
"positions only for objects the web DB does not know yet".

# The three passes, and why there are three

Pass 1 (the probe's snapshot): emit ONE `query` over the page. The graph rides
along in `hop.canvy_graph`, which the hive's `./layout -> ./web` edge promotes
into `context` -- `hop` survives exactly one edge, and pass 2 is two edges away
(layout -> web -> layout). Carrying it in `hop` alone would lose it silently, the
same trap the 1.x render cell fell into with a drop's coordinates.

Pass 2 (the display answered): compute the layout against the objects that exist
and emit one bundle of `object.*` calls. A refusal here is not a failure but the
BOOTSTRAP case: a `web` cell whose page has never been set answers `query` with
`invalid_input`, which is the only honest signal that this display is empty, and
the same bundle then defines the components, creates the root and sets the page.

Pass 3 (the display acknowledged the patch): emit NOTHING. This pass is the whole
reason the cell needs a discriminator at all. Before the equivalent check existed
in 1.x, every store acknowledgement fell through to "ask again" -- one tick became
two, two became four, and the routing loop wedged on a full mailbox inside twenty
seconds (GH #161). A cell that cannot recognise the reply to its own write has no
way to stop.
"""
